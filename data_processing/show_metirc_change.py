    # 5. 坐标轴 & 标题（全部加大字体）
    # ======================
    plt.xlabel(xlabel_name, fontsize=24)
    plt.ylabel(ylabel_name, fontsize=24)
    plt.title(label, fontsize=28)

    plt.xticks(missing_rates, fontsize=20)
    plt.yticks(fontsize=20)

    plt.legend(fontsize=20)

